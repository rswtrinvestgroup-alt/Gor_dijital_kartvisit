const langCodes = { tr: 'TR', ru: 'RU', hy: 'HY', es: 'ES', en: 'EN' };

let currentLang = localStorage.getItem('gor-lang') || 'tr';

const langToggle = document.getElementById('lang-toggle');
const langMenu = document.getElementById('lang-menu');
const langCurrent = document.getElementById('lang-current');

function closeLangMenu() {
  langMenu.classList.remove('open');
  langMenu.hidden = true;
  langToggle.setAttribute('aria-expanded', 'false');
}

function openLangMenu() {
  closeEmailMenu();
  langMenu.hidden = false;
  requestAnimationFrame(() => langMenu.classList.add('open'));
  langToggle.setAttribute('aria-expanded', 'true');
}

function toggleLangMenu() {
  if (langMenu.classList.contains('open')) {
    closeLangMenu();
  } else {
    openLangMenu();
  }
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('gor-lang', lang);
  document.documentElement.lang = lang;

  const t = translations[lang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) el.textContent = t[key];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key]) el.placeholder = t[key];
  });

  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    const key = el.getAttribute('data-i18n-alt');
    if (t[key]) el.alt = t[key];
  });

  if (t.pageTitle) document.title = t.pageTitle;

  const whatsappCta = document.getElementById('whatsapp-cta');
  if (whatsappCta && t.whatsappCTAMsg) {
    whatsappCta.href = `https://wa.me/79220918218?text=${encodeURIComponent(t.whatsappCTAMsg)}`;
  }

  if (langCurrent) langCurrent.textContent = langCodes[lang] || lang.toUpperCase();

  document.querySelectorAll('.lang-option').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

langToggle.addEventListener('click', (e) => {
  e.stopPropagation();
  toggleLangMenu();
});

document.querySelectorAll('.lang-option').forEach(btn => {
  btn.addEventListener('click', () => {
    setLanguage(btn.dataset.lang);
    closeLangMenu();
  });
});

document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape') {
    closeLangMenu();
    closeEmailMenu();
  }
});

const emailToggle = document.getElementById('email-toggle');
const emailMenu = document.getElementById('email-menu');
const toast = document.getElementById('toast');
let toastTimer;

function closeEmailMenu() {
  emailMenu.classList.remove('open');
  emailMenu.hidden = true;
  emailToggle.setAttribute('aria-expanded', 'false');
}

function openEmailMenu() {
  closeLangMenu();
  emailMenu.hidden = false;
  requestAnimationFrame(() => emailMenu.classList.add('open'));
  emailToggle.setAttribute('aria-expanded', 'true');
}

function toggleEmailMenu() {
  if (emailMenu.classList.contains('open')) {
    closeEmailMenu();
  } else {
    openEmailMenu();
  }
}

function showToast(message) {
  toast.textContent = message;
  toast.classList.add('show');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => toast.classList.remove('show'), 2500);
}

async function copyEmail() {
  try {
    await navigator.clipboard.writeText(EMAIL);
    showToast(translations[currentLang].emailCopied);
  } catch {
    const input = document.createElement('input');
    input.value = EMAIL;
    document.body.appendChild(input);
    input.select();
    document.execCommand('copy');
    document.body.removeChild(input);
    showToast(translations[currentLang].emailCopied);
  }
}

emailToggle.addEventListener('click', (e) => {
  e.stopPropagation();
  toggleEmailMenu();
});

document.querySelectorAll('.email-option').forEach(btn => {
  btn.addEventListener('click', async () => {
    const action = btn.dataset.action;
    closeEmailMenu();
    if (action === 'copy') {
      await copyEmail();
    } else if (action === 'gmail') {
      window.open(EMAIL_URLS.gmail, '_blank');
    } else if (action === 'outlook') {
      window.open(EMAIL_URLS.outlook, '_blank');
    }
  });
});

document.addEventListener('click', (e) => {
  if (!e.target.closest('.lang-switcher')) closeLangMenu();
  if (!e.target.closest('.email-switcher')) closeEmailMenu();
});

document.getElementById('lead-form').addEventListener('submit', function (e) {
  e.preventDefault();
  const phone = document.getElementById('phone-input').value.trim();
  if (!phone) {
    document.getElementById('phone-input').focus();
    return;
  }
  const t = translations[currentLang];
  const message = t.whatsappFormMsg.replace('{phone}', phone);
  window.open(`https://wa.me/79220918218?text=${encodeURIComponent(message)}`, '_blank');
});

